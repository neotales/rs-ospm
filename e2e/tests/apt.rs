//! End-to-end tests for the APT process backend against a disposable container.
//!
//! The real `Apt` driver runs on the host and spawns wrapper scripts that
//! `docker exec` only into the container this test started. No host package
//! operation, privilege escalation, bind mount, or published port is used. The
//! container is removed by testcontainers when the test ends.
//!
//! Only Unix hosts are supported: the injection wrappers are POSIX shell
//! scripts. Opt in with `NEOTALES_OSPM_E2E=1`; otherwise the test reports a
//! skip and returns without touching Docker.
#![cfg(unix)]
#![forbid(unsafe_code)]

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use neotales_ospm_apt_cli::Apt;
use neotales_ospm_core::{
    Install, List, Package, PackageName, Pin, QueryOptions, Remove, Search, Update, UpdateSources,
};
use testcontainers::{
    Container, GenericImage, ImageExt,
    core::{ExecCommand, WaitFor},
    runners::SyncRunner,
};

type Error = Box<dyn std::error::Error + Send + Sync>;

const IMAGE: &str = "debian";
/// `debian:12-slim`, resolved to its multi-architecture index digest with
/// `docker pull debian:12-slim` and
/// `docker image inspect --format '{{index .RepoDigests 0}}' debian:12-slim`
/// on 2026-11-21. The tag text cannot override the content digest.
const IMAGE_TAG: &str =
    "12-slim@sha256:734a72b3d6142a71993b4bc580ca01d8ca687f77a2c422d96a961d3376b179bc";

/// Set to `1` to run this test. Anything else leaves Docker untouched.
const OPT_IN: &str = "NEOTALES_OSPM_E2E";
/// A dependency-light package that is not installed in the base image.
const PACKAGE: &str = "hello";

fn docker_available() -> bool {
    Command::new("docker")
        .arg("info")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .is_ok_and(|status| status.success())
}

/// Runs a command in the container and returns its standard output.
fn exec(container: &Container<GenericImage>, command: &[&str]) -> Result<String, Error> {
    let mut result = container.exec(ExecCommand::new(command.iter().copied()))?;
    let stdout = result.stdout_to_vec()?;
    let stderr = result.stderr_to_vec()?;
    let code = result.exit_code()?;
    if code != Some(0) {
        return Err(format!(
            "container command {command:?} exited with {code:?}: {}",
            String::from_utf8_lossy(&stderr)
        )
        .into());
    }
    Ok(String::from_utf8(stdout)?)
}

/// Writes an executable that forwards its arguments to one tool in the container.
///
/// The container id is generated by Docker and the tool name is a constant, so
/// the shell text contains no caller-provided input beyond the forwarded
/// arguments, which are positional and never re-parsed.
fn wrapper(directory: &Path, name: &str, tool: &str, container_id: &str) -> Result<PathBuf, Error> {
    let path = directory.join(name);
    fs::write(
        &path,
        format!(
            "#!/bin/sh\nexec docker exec --interactive \
             --env LC_ALL=C --env DEBIAN_FRONTEND=noninteractive \
             '{container_id}' {tool} \"$@\"\n"
        ),
    )?;
    fs::set_permissions(&path, fs::Permissions::from_mode(0o700))?;
    Ok(path)
}

fn holds(container: &Container<GenericImage>) -> Result<Vec<String>, Error> {
    Ok(exec(container, &["apt-mark", "showhold"])?
        .lines()
        .filter(|line| !line.trim().is_empty())
        .map(str::to_owned)
        .collect())
}

fn find<'a>(packages: &'a [Package], name: &str) -> Option<&'a Package> {
    packages.iter().find(|package| package.name == name)
}

#[test]
fn apt_cli_backend_against_a_disposable_debian_container() -> Result<(), Error> {
    if std::env::var(OPT_IN).as_deref() != Ok("1") {
        eprintln!("skipping APT container e2e: set {OPT_IN}=1 to run it");
        return Ok(());
    }
    if !docker_available() {
        return Err(format!(
            "{OPT_IN}=1 but the Docker daemon is unavailable; start Docker or unset {OPT_IN}"
        )
        .into());
    }

    let container = GenericImage::new(IMAGE, IMAGE_TAG)
        .with_wait_for(WaitFor::seconds(1))
        .with_cmd(["sleep", "infinity"])
        .start()?;

    // Configure apt to assume yes and keep conffiles inside this container
    // only. The driver intentionally adds no non-interactive options itself.
    exec(
        &container,
        &[
            "sh",
            "-c",
            "printf '%s\\n' 'APT::Get::Assume-Yes \"true\";' \
             'Dpkg::Options { \"--force-confdef\"; \"--force-confold\"; };' \
             > /etc/apt/apt.conf.d/99-ospm-e2e",
        ],
    )?;

    let scripts = tempfile::tempdir()?;
    let apt_get = wrapper(scripts.path(), "apt-get", "apt-get", container.id())?;
    let apt_cache = wrapper(scripts.path(), "apt-cache", "apt-cache", container.id())?;
    let dpkg_query = wrapper(scripts.path(), "dpkg-query", "dpkg-query", container.id())?;
    let apt_mark = wrapper(scripts.path(), "apt-mark", "apt-mark", container.id())?;

    // The documented injection interface: an explicit executable path plus the
    // read-only tools. Every spawned process is a wrapper around this container.
    let apt = Apt::with_executable(apt_get.as_path()).with_tools(
        apt_cache.as_path(),
        dpkg_query.as_path(),
        apt_mark.as_path(),
    );

    let options = QueryOptions::default();
    let installed = apt.list("", &options)?;
    let bash = find(&installed, "bash")
        .ok_or("the container did not report bash as installed through dpkg-query")?;
    assert_ne!(bash.version, "");

    let bash_name = PackageName::new("bash")?;
    apt.pin(&bash_name)?;
    assert!(holds(&container)?.iter().any(|name| name == "bash"));
    apt.unpin(&bash_name)?;
    assert_eq!(holds(&container)?.len(), 0);

    apt.update_sources()?;
    let found = apt.search("^hello$", &options)?;
    let candidate =
        find(&found, PACKAGE).ok_or("the container did not find hello through apt-cache")?;
    assert_ne!(candidate.version, "");
    assert!(
        candidate
            .metadata
            .get("architecture")
            .is_some_and(|architecture| !architecture.is_empty())
    );

    apt.update(&bash_name)?;

    let package = PackageName::new(PACKAGE)?;
    apt.install(&package)?;
    let installed = apt.list(PACKAGE, &options)?;
    let hello = find(&installed, PACKAGE).ok_or("hello is not installed after install")?;
    assert_eq!(hello.version, candidate.version);

    apt.remove(&package)?;
    assert!(find(&apt.list(PACKAGE, &options)?, PACKAGE).is_none());

    Ok(())
}
